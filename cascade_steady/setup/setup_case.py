#!/usr/bin/env python3
"""
Build one cascade case directory (called by run_script; also usable on its own).

    python3 setup_case.py CASE_DIR --solver rhoSimpleFoam|simpleFoam --inlet PIBC|VIBC
                          --Tu 0.8 [--beta 30] [--iterations 3000] [--init-iterations 1000]
                          [--U 84] [--mesh ag5|<name>] [--numerics h|v1712] [--wall lowRe|spalding]

Consigny and Richards (1982) case A, Spalart-Allmaras.
  rhoSimpleFoam : CASE_DIR is the compressible case; CASE_DIR/init is the simpleFoam run
                  that initialises it (the v1712 workflow)
  simpleFoam    : CASE_DIR is the incompressible comparison case
Inlet: PIBC = total pressure 127.5 kPa and total temperature 419 K (velocity from the solution);
       VIBC = velocity --U along beta (default 84 m/s, the pressure-inlet value; 97.91 m/s is the
       reported inlet Mach number of 0.24). Outlet: mean static pressure 98 384 Pa.
Inlet nuTilda = sqrt(3/2) V1 Tu l, with V1 = 97.91 m/s (M1 = 0.24) and l = 0.07 c (as v1712).
Mesh: ag5 = the AutoGrid5 mesh (mesh/polyMesh.tar.gz, as v1712); any other name = mesh/<name>/,
      holding polyMesh.tar.gz or a polyMesh/ folder, and optionally a 'patchmap' file of
      'old_name new_name' lines to rename its inlet, outlet and blade patches to row_1_INFLOW,
      row_1_OUTFLOW and row_1_BLADE. Periodic (cyclic or cyclicAMI) and empty patches need no
      renaming: the field files set them by patch type.
rhoPimpleFoam : time-accurate version of the compressible case (see transient()): Chapter 5 numerics,
                --dt, --endTime, time means from --avgStart; initialised from CASE/init as above
Numerics (rhoSimpleFoam): h = sensible enthalpy and standard SIMPLE (default; see enthalpy_numerics);
      h_lim = h with cell-limited gradients (see limited_gradients); v1712 = the template as v1712 had it
      (internal energy, SIMPLEC), kept for the version check.
Standard library only.
"""
import argparse, json, math, os, re, shutil, tarfile, tempfile

ROOT = os.path.dirname(os.path.abspath(__file__))
P0, T0, P_OUT, T_WALL, CHORD, CP = 127500.0, 419.0, 98384.0, 296.0, 0.08, 1004.0
M1 = 0.24                                                    # reported inlet Mach number
V_NOMINAL = M1 * math.sqrt(1.4 * 287.0 * T0 / (1 + 0.2 * M1 ** 2))   # 97.91 m/s, as v1712
U_VIBC = 84.0                                                # effective inlet velocity from the PIBC runs
NEEDED = ("row_1_INFLOW", "row_1_OUTFLOW", "row_1_BLADE")


def install_mesh(spec, constant):
    """put the mesh into constant/polyMesh; returns a description"""
    if spec == "ag5":
        src = os.path.join(ROOT, "mesh", "polyMesh.tar.gz")
        mapfile = None
    else:
        base = os.path.join(ROOT, "mesh", spec)
        src = os.path.join(base, "polyMesh.tar.gz")
        if not os.path.isfile(src):
            src = os.path.join(base, "polyMesh")
        mapfile = os.path.join(base, "patchmap")
    if not os.path.exists(src):
        raise SystemExit(f"mesh not found: {src}")
    dst = os.path.join(constant, "polyMesh")
    if os.path.isdir(src):
        shutil.copytree(src, dst)
    else:
        tmp = tempfile.mkdtemp(dir=constant)
        with tarfile.open(src) as tf:
            tf.extractall(tmp)
        found = [r for r, ds, fs in os.walk(tmp) if os.path.basename(r) == "polyMesh" and "boundary" in fs]
        if not found:
            raise SystemExit(f"no polyMesh/boundary inside {src}")
        shutil.move(found[0], dst)
        shutil.rmtree(tmp)
    bnd = os.path.join(dst, "boundary")
    text = open(bnd).read()
    if mapfile and os.path.isfile(mapfile):
        for line in open(mapfile):
            w = line.split("#")[0].split()
            if len(w) == 2:
                text = re.sub(r"\b%s\b" % re.escape(w[0]), w[1], text)   # keys and neighbourPatch entries
        open(bnd, "w").write(text)
    missing = [n for n in NEEDED if not re.search(r"^\s*%s\s*$" % n, text, re.M)]
    if missing:
        raise SystemExit(f"mesh {spec}: patch(es) {', '.join(missing)} not found in constant/polyMesh/boundary "
                         f"- add a mesh/{spec}/patchmap file")
    return src


def build(src, dst, inlet, params, mesh):
    shutil.copytree(src, dst)
    for f in ("U", "p"):                                     # pick the inlet variant, fix the header name
        keep = os.path.join(dst, "0", f"{f}.{inlet}")
        txt = open(keep).read().replace(f"object      {f}.{inlet};", f"object      {f};")
        open(os.path.join(dst, "0", f), "w").write(txt)
        for v in ("PIBC", "VIBC"):
            os.remove(os.path.join(dst, "0", f"{f}.{v}"))
    install_mesh(mesh, os.path.join(dst, "constant"))
    open(os.path.join(dst, "case.foam"), "w").close()
    with open(os.path.join(dst, "caseParameters"), "w") as fh:
        fh.write("// Generated by setup_case.py\n")
        for k, v in params.items():
            fh.write(f"{k:15s} {v};\n" if isinstance(v, str) else f"{k:15s} {v:.10g};\n")


def subn1(path, pattern, repl):
    """one regex replacement in a case file; stop if the pattern isn't there exactly once"""
    txt = open(path).read()
    new, n = re.subn(pattern, repl, txt)
    if n != 1:
        raise SystemExit(f"{path}: expected one match for {pattern!r}, found {n} - template changed?")
    open(path, "w").write(new)


# rhoSimpleFoam relaxation by numerics name: (SIMPLEC, p field, U and nuTilda equations, h equation)
RELAX = {"h": (False, "0.3", "0.7", "0.5"), "h_soft": (False, "0.2", "0.5", "0.3"),
         "h_u90": (False, "0.1", "0.9", "0.7"), "hc_u90": (True, "0.3", "0.9", "0.7"), "hc_u95": (True, "0.3", "0.95", "0.8"),
         "hc_u97": (True, "0.3", "0.97", "0.85"), "hc_u98": (True, "0.3", "0.98", "0.9")}


def enthalpy_numerics(case, soft=False, name=None):
    """
    Compressible numerics for v2606 (diag_pibc.sh, 3 Nov, variant simple_h05): energy as sensible
    enthalpy, standard SIMPLE, p 0.3, rho 0.05, U and nuTilda 0.7, h 0.5. With the v1712 settings
    (SIMPLEC, internal energy) the pressure inlet breaks down in v2606: the energy residual grows
    until the run fails. simple_h05 at 1 000 iterations: inlet 84.0 m/s, Fy/Fz 1 071/1 310 N/m,
    surface pressure 0.057% mean from v1712 PIBC at the same iteration.
    soft (numerics h_soft): the same with heavier under-relaxation, p 0.2, U and nuTilda 0.5, h 0.3,
    for the snappyHexMesh V02 fine level, which diverged with h (5 Nov: PIBC at iteration 1 030 in the
    pressure solver, VIBC at iteration 49).
    h_u90, hc_u90, hc_u95 (11 Nov): LESS under-relaxation of U, nuTilda and h (0.9 / 0.95), with SIMPLE (h_u90,
    p 0.1) or SIMPLEC (hc_*, p 0.3). An equation relaxation factor a acts as a pseudo-time step of about
    a / (1 - a) cell-transit times, and an implicit step damps an oscillation of angular frequency w only when
    w dt is large enough. With U 0.7 the trailing-edge shedding (15.9 kHz on the fine snappyHexMesh level)
    takes about 34 iterations per period, which is what the diverging fine-level runs show, and is not damped;
    0.9 and 0.95 make the step about 4 and 8 times longer. h_soft (0.5) went the other way and failed on
    every mesh. See Ch2_SHM/V04/README.md.
    hc_u97, hc_u98 (11 Nov): for the extra-fine uniform level (89 um cells at the trailing edge), where 0.95 no
    longer damps the shedding: started from the fine level's converged field it settled for 75 iterations, then an
    oscillation grew until the run failed at iteration 507. The pseudo-time step scales with the cell size, so a
    mesh 1.4 times finer needs a / (1 - a) about 1.4 times larger: 0.97 gives 1.7 times, 0.98 gives 2.6 times.
    """
    simplec, rp, ru, rh = RELAX[name or ("h_soft" if soft else "h")]
    subn1(os.path.join(case, "constant", "thermophysicalProperties"),
          r"energy\s+sensibleInternalEnergy;", "energy          sensibleEnthalpy;")
    subn1(os.path.join(case, "system", "fvSchemes"), r"(\n(\s*)div\(phi,U\)[^\n]*)",
          r"\1\n\2div(phi,h)      bounded Gauss linearUpwind grad(h);\n\2div(phi,K)      bounded Gauss upwind;")
    fvs = os.path.join(case, "system", "fvSolution")
    subn1(fvs, r'"\(U\|e\|nuTilda\)"', '"(U|e|h|nuTilda)"')
    if not simplec:
        subn1(fvs, r"consistent\s+yes;[^\n]*", "consistent      no;                 // SIMPLE (v1712: SIMPLEC, unstable "
              "with the pressure inlet in v2606)")
    subn1(fvs, r"(?s)relaxationFactors\s*\{.*?\n\}", f"relaxationFactors\n{{\n    fields\n    {{\n        p               {rp};\n"
          f"        rho             0.05;\n    }}\n    equations\n    {{\n        p               0.9;\n        U               {ru};\n"
          f"        h               {rh};\n        nuTilda         {ru};\n    }}\n}}")
    subn1(os.path.join(case, "system", "cascadeFunctions"), r"fields\s+\(U p e nuTilda\);", "fields          (U p h nuTilda);")


def limited_gradients(case):
    """
    Numerics h_lim: h, with the velocity, enthalpy and nuTilda gradients cell-limited (Gauss linear, limiter 1)
    instead of face-limited 0.5, so the linearUpwind reconstruction stays bounded where the flow separates.
    For the snappyHexMesh fine level: with h its steady run oscillates in the separated flow at the base of the
    trailing-edge circle (pressure-side half) and diverges (5 Nov, V02 and V03c alike). Use it for the AutoGrid5
    reference too, so items 7-8 compare meshes at the same numerics.
    """
    fs = os.path.join(case, "system", "fvSchemes")
    subn1(fs, r"grad\(U\)\s+faceLimited Gauss linear 0\.5;", "grad(U)         cellLimited Gauss linear 1;")
    subn1(fs, r"grad\(e\)\s+faceLimited Gauss linear 0\.5;", "grad(h)         cellLimited Gauss linear 1;")
    subn1(fs, r"grad\(nuTilda\)\s+faceLimited Gauss linear 0\.5;", "grad(nuTilda)   cellLimited Gauss linear 1;")


def transonic(case):
    """
    Numerics h_trans: h with SIMPLE's transonic formulation (the density change enters the pressure equation
    implicitly through div(phid,p), already in the template's fvSchemes). For item 2: a velocity inlet at the
    reported 97.91 m/s with the reported outlet pressure needs about 30% more inlet total pressure than the
    experiment and takes the passage close to choking (1D estimate, 6 Nov), and the continuation from A1_VIBC
    with transonic off diverged at about 93 m/s.
    """
    subn1(os.path.join(case, "system", "fvSolution"), r"transonic\s+no;",
          "transonic       yes;                // h_trans: passage close to choking (item 2)")


TRANSIENT_FOS = """
// Transient runs (rhoPimpleFoam, added by setup_case.py): time means from avgStart, and the inlet and outlet
// states of the mean fields for the loss coefficient. The blade surface sample above also writes pMean.
timeMeans
{
    type            fieldAverage;
    libs            (fieldFunctionObjects);
    timeStart       $avgStart;
    writeControl    writeTime;
    fields
    (
        p { mean on; prime2Mean off; base time; }
        U { mean on; prime2Mean off; base time; }
        T { mean on; prime2Mean off; base time; }
    );
}
inletMean
{
    type            surfaceFieldValue;
    libs            (fieldFunctionObjects);
    timeStart       $avgStart;
    writeControl    writeTime;
    log             false;
    writeFields     false;
    regionType      patch;
    name            row_1_INFLOW;
    operation       weightedAverage;
    weightField     phi;
    fields          (UMean pMean TMean);
}
outletMean
{
    $inletMean;
    name            row_1_OUTFLOW;
}
"""


def transient(case):
    """
    rhoPimpleFoam (time-accurate) variant of the compressible case, for the Chapter 2 runs the steady solver
    can't settle: the snappyHexMesh fine level (6 Nov: both inlets diverge at the trailing-edge base, two layer
    designs, with or without gradient limiting) and AutoGrid5 above about 88 m/s at the velocity inlet.
    Numerics as Chapter 5 (template_transient: internal energy, PIMPLE with 2 outer and 2 pressure correctors,
    Euler); fixed time step dt, run to endTime, time means (pMean, UMean, TMean) from avgStart. The boundary
    conditions, mesh handling and initialisation (simpleFoam run in CASE/init) are those of the steady case.
    """
    sysd = os.path.join(case, "system")
    for f in ("fvSchemes", "fvSolution"):
        shutil.copy(os.path.join(ROOT, "template_transient", "system", f), os.path.join(sysd, f))
    cd = os.path.join(sysd, "controlDict")
    subn1(cd, r"application\s+rhoSimpleFoam;", "application     rhoPimpleFoam;")
    subn1(cd, r"endTime\s+\$iterations;[^\n]*", "endTime         $endTime;")
    # Courant-limited time step (6 Nov): on the snappyHexMesh meshes the first step at a fixed 5e-7 s had a
    # maximum Courant number of 13 and the energy solve failed. The step starts at 1e-8 s, grows by at most
    # 20% a step, and is held at min(dt, the step giving maxCo). AutoGrid5 (max Co about 1.1 at 5e-7 s) runs
    # at dt as before; Gate 3 found the results insensitive to the step up to a max Co of about 4.
    subn1(cd, r"deltaT\s+1;", "deltaT          1e-08;\nadjustTimeStep  yes;\nmaxCo           $maxCo;\nmaxDeltaT       $dt;")
    subn1(cd, r"writeControl\s+timeStep;", "writeControl    adjustableRunTime;")
    subn1(cd, r"writeInterval\s+\$writeRho;[^\n]*", "writeInterval   $writeInterval;")
    subn1(cd, r"purgeWrite\s+0;", "purgeWrite      3;")
    subn1(cd, r"timePrecision\s+6;", "timePrecision   8;")
    fo = os.path.join(sysd, "cascadeFunctions")
    subn1(fo, r"fields\s+\(p\);", "fields          (p pMean);")
    with open(fo, "a") as fh:
        fh.write(TRANSIENT_FOS)


SCHEMES = ("base", "ho_K", "ho_unlim", "ho_lsq", "ho_lust")


def higher_order(case, name):
    """
    Discretisation variants for the steady compressible runs (11 Nov; --schemes, SCHEMES= in run_script).
    OpenFOAM's finite-volume schemes are second order at most; these remove what is below that in 'base':
      base      as before: linearUpwind with face-limited gradients (0.5) for U and nuTilda; the kinetic-energy
                term of the enthalpy equation, div(phi,K), first-order upwind
      ho_K      div(phi,K) second order (linearUpwind on a cell-limited gradient): every convective term second order
      ho_unlim  ho_K, and the gradients of U and nuTilda unlimited (Gauss linear): no limiter left on momentum
      ho_lsq    ho_unlim with least-squares gradients, which stay second order on the snappyHexMesh mesh's
                hanging-node cells where Gauss linear loses accuracy
      ho_lust   ho_unlim with LUST for momentum (75% central, 25% linearUpwind): the least dissipative of the set
    """
    if name == "base":
        return
    fs = os.path.join(case, "system", "fvSchemes")
    subn1(fs, r"div\(phi,K\)\s+bounded Gauss upwind;", "div(phi,K)      bounded Gauss linearUpwind limited;")
    subn1(fs, r"(\n(\s*)grad\(p\)[^\n]*)", r"\1\n\2limited         cellLimited Gauss linear 1;")
    if name in ("ho_unlim", "ho_lsq", "ho_lust"):
        g = "leastSquares" if name == "ho_lsq" else "Gauss linear"
        subn1(fs, r"grad\(U\)\s+faceLimited Gauss linear 0\.5;", f"grad(U)         {g};")
        subn1(fs, r"grad\(nuTilda\)\s+faceLimited Gauss linear 0\.5;", f"grad(nuTilda)   {g};")
    if name == "ho_lsq":
        subn1(fs, r"default\s+Gauss linear;[^\n]*", "default         leastSquares;")
        subn1(fs, r"grad\(p\)\s+Gauss linear;", "grad(p)         leastSquares;")
        subn1(fs, r"limited\s+cellLimited Gauss linear 1;", "limited         cellLimited leastSquares 1;")
    if name == "ho_lust":
        subn1(fs, r"div\(phi,U\)\s+Gauss linearUpwind grad\(U\);", "div(phi,U)      bounded Gauss LUST grad(U);")


def spalding_wall(case):
    """nut on the blade from Spalding's law of the wall (valid from y+ < 1 into the log layer) instead of
    resolving the wall; for meshes without boundary-layer layers. nuTilda stays 0 at the wall."""
    subn1(os.path.join(case, "0", "nut"), r"(row_1_BLADE\s*\{\s*type\s+)calculated;", r"\1nutUSpaldingWallFunction;")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("case")
    ap.add_argument("--solver", choices=("rhoSimpleFoam", "rhoPimpleFoam", "simpleFoam"), required=True)
    ap.add_argument("--dt", type=float, default=5e-7, help="rhoPimpleFoam: time step, s (Chapter 5 batch value)")
    ap.add_argument("--endTime", type=float, default=0.016, help="rhoPimpleFoam: run length, s")
    ap.add_argument("--avgStart", type=float, default=0.006, help="rhoPimpleFoam: start of the time means, s")
    ap.add_argument("--maxCo", type=float, default=4.0, help="rhoPimpleFoam: Courant limit on the time step (max step --dt)")
    ap.add_argument("--inlet", choices=("PIBC", "VIBC"), required=True)
    ap.add_argument("--Tu", type=float, required=True, help="free-stream turbulence intensity, percent")
    ap.add_argument("--beta", type=float, default=30.0, help="inlet flow angle, degrees (design 30)")
    ap.add_argument("--iterations", type=int, default=3000)
    ap.add_argument("--init-iterations", type=int, default=1000)
    ap.add_argument("--U", type=float, default=U_VIBC, help="velocity-inlet speed, m/s (default 84)")
    ap.add_argument("--mesh", default="ag5", help="ag5 (default) or a folder name under mesh/")
    ap.add_argument("--numerics", choices=("h", "h_soft", "h_lim", "h_trans", "h_u90", "hc_u90", "hc_u95", "hc_u97", "hc_u98", "v1712"), default="h",
                    help="rhoSimpleFoam: h = sensible enthalpy, SIMPLE (default); h_soft = the same, more under-relaxed; "
                         "h_lim = h with cell-limited gradients; h_trans = h with the transonic formulation; "
                         "h_u90, hc_u90, hc_u95 = h with U, nuTilda and h relaxed less (0.9 / 0.95; hc = SIMPLEC); "
                         "v1712 = internal energy, SIMPLEC")
    ap.add_argument("--schemes", choices=SCHEMES, default="base", help="rhoSimpleFoam discretisation variant (see higher_order)")
    ap.add_argument("--wall", choices=("lowRe", "spalding"), default="lowRe",
                    help="blade: lowRe = wall resolved, y+ about 1 (default, as v1712); spalding = Spalding wall function")
    a = ap.parse_args()

    b = math.radians(a.beta)
    it_inc = a.iterations if a.solver == "simpleFoam" else a.init_iterations
    # OpenFOAM writes only on the write interval, not automatically at endTime: write every 1 000
    # iterations (the v1712 version-check point), or once at the end if the run isn't a multiple
    # of 1 000 (the 200 + 300 iteration smoke test)
    every = lambda n: 1000 if n % 1000 == 0 else n
    unsteady = a.solver == "rhoPimpleFoam"
    numerics = {"rhoSimpleFoam": a.numerics, "rhoPimpleFoam": "transient"}.get(a.solver, "incompressible")
    p = dict(solver=a.solver, inletType=a.inlet, Tu=a.Tu, beta=a.beta, meshType=a.mesh.replace("/", "_"),
             numerics=numerics, schemes=a.schemes, wall=a.wall, Uin=a.U, nuTildaInlet=math.sqrt(1.5) * V_NOMINAL * a.Tu / 100.0 * 0.07 * CHORD,
             dirY=math.sin(b), dirZ=math.cos(b),
             Uy0=a.U * math.sin(b), Uz0=a.U * math.cos(b),
             p0Inlet=P0, T0Inlet=T0, pOutlet=P_OUT, Twall=T_WALL,
             Tinlet=T0 - a.U ** 2 / (2 * CP),
             iterations=a.iterations, iterationsInc=it_inc,
             writeRho=every(a.iterations), writeInc=every(it_inc))
    if unsteady:
        if not 0 < a.avgStart < a.endTime:
            raise SystemExit("--avgStart must lie between 0 and --endTime")
        # write every 2 ms; short (smoke-test) runs write four times so the means get sampled
        p.update(dt=a.dt, endTime=a.endTime, avgStart=a.avgStart, maxCo=a.maxCo,
                 writeInterval=0.002 if a.endTime >= 0.008 else float(f"{a.endTime / 4:.3g}"))
    case = os.path.abspath(a.case)
    if os.path.exists(case):
        shutil.rmtree(case)
    if a.solver == "simpleFoam":
        build(os.path.join(ROOT, "template_inc"), case, a.inlet, p, a.mesh)
    else:
        build(os.path.join(ROOT, "template_rho"), case, a.inlet, p, a.mesh)
        if unsteady:
            transient(case)
        elif a.numerics in ("h", "h_soft", "h_lim", "h_trans") or a.numerics in RELAX:
            enthalpy_numerics(case, name=a.numerics if a.numerics in RELAX else "h")
        if not unsteady and a.numerics == "h_lim":
            limited_gradients(case)
        if not unsteady and a.numerics == "h_trans":
            transonic(case)
        if not unsteady and a.schemes != "base":
            if a.numerics not in RELAX:
                raise SystemExit("--schemes needs one of the enthalpy numerics")
            higher_order(case, a.schemes)
        build(os.path.join(ROOT, "template_inc"), os.path.join(case, "init"), a.inlet, p, a.mesh)
        if a.wall == "spalding":
            spalding_wall(os.path.join(case, "init"))
    if a.wall == "spalding":
        spalding_wall(case)
    json.dump(dict(case=os.path.basename(case), **p), open(os.path.join(case, "setup.json"), "w"), indent=1)
    print(f"{os.path.basename(case)}: {a.solver} {a.inlet}" + (f" {a.U:g} m/s" if a.inlet == "VIBC" else "")
          + f"  Tu {a.Tu}%  beta {a.beta:g} deg  mesh {a.mesh}  nuTilda {p['nuTildaInlet']:.6g} m2/s  "
          + (f"to {a.endTime:g} s at a step of at most {a.dt:g} s and max Co {a.maxCo:g}, means from {a.avgStart:g} s"
             if unsteady else f"iterations {a.iterations}")
          + (f"  numerics {a.numerics}" if a.solver == "rhoSimpleFoam" else "")
          + (f"  wall {a.wall}" if a.wall != "lowRe" else "")
          + (f" (initialised by {a.init_iterations} simpleFoam iterations)" if a.solver != "simpleFoam" else ""))


if __name__ == "__main__":
    main()
